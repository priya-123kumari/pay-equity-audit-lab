"""Step 9: CSV / JSON / SQL export, ground truth, manifest and checksums."""
import hashlib, json, numbers, os
import pandas as pd
from .schema import SCHEMA, columns


def _prep(name, df):
    out = df[columns(name)].copy()
    for c in SCHEMA[name]["cols"]:
        nm, typ = c[0], c[1]
        if typ in ("BOOLEAN", "INTEGER"):
            out[nm] = out[nm].astype("float").round().astype("Int64") if typ == "INTEGER" else out[nm].astype("Int64")
        elif typ == "REAL":
            out[nm] = out[nm].astype(float)
    return out


def ddl():
    sql_t = {"TEXT": "TEXT", "INTEGER": "INTEGER", "REAL": "REAL", "DATE": "DATE", "BOOLEAN": "INTEGER"}
    lines = ["-- Auto-generated from generator/schema.py", "PRAGMA foreign_keys = ON;", ""]
    for name, spec in SCHEMA.items():
        cols, fks = [], []
        for nm, typ, req, allowed, unit, uniq, rule, fk in spec["cols"]:
            d = f"  {nm} {sql_t[typ]}"
            if req or nm in spec["pk"]:
                d += " NOT NULL"
            if uniq and len(spec["pk"]) == 1 and nm in spec["pk"]:
                pass
            elif uniq:
                d += " UNIQUE"
            if typ == "BOOLEAN":
                d += f" CHECK ({nm} IN (0,1))"
            if allowed:
                d += f" CHECK ({nm} IN ({', '.join(repr(a) if isinstance(a, int) else repr(a) for a in allowed)}))"
            cols.append(d)
            if fk:
                t, c = fk.split("."); fks.append(f"  FOREIGN KEY ({nm}) REFERENCES {SCHEMA[t]['file']}({c}) DEFERRABLE INITIALLY DEFERRED")
        pk = f"  PRIMARY KEY ({', '.join(spec['pk'])})"
        lines.append(f"CREATE TABLE {spec['file']} (\n" + ",\n".join(cols + [pk] + fks) + "\n);\n")
    return "\n".join(lines)


def _lit(v):
    if v is None or v is pd.NA or (isinstance(v, float) and v != v):
        return "NULL"
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    if isinstance(v, numbers.Integral):
        return str(int(v))
    return repr(float(v))


def seed_sql(P):
    out = ["-- Seed data (INSERTs). Load schema.sql first. FKs are DEFERRABLE INITIALLY DEFERRED so one transaction loads everything.", "BEGIN;"]
    for name, spec in SCHEMA.items():
        df = P[name]; cols = ", ".join(df.columns)
        for i in range(0, len(df), 500):
            vals = ",\n".join("(" + ", ".join(_lit(v) for v in row) + ")" for row in df.iloc[i:i + 500].itertuples(index=False, name=None))
            out.append(f"INSERT INTO {spec['file']} ({cols}) VALUES\n{vals};")
    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def export_all(R, out_dir, validation, metrics, command):
    cfg = R["config"]
    for sub in ("csv", "json", "sql", "ground_truth", "outputs", "manifest"):
        os.makedirs(os.path.join(out_dir, sub), exist_ok=True)
    P = {n: _prep(n, R["tables"][n]) for n in SCHEMA}
    rows = {}
    for n, df in P.items():
        f = SCHEMA[n]["file"]
        df.to_csv(os.path.join(out_dir, "csv", f"{f}.csv"), index=False, lineterminator="\n")
        df.to_json(os.path.join(out_dir, "json", f"{f}.json"), orient="records", force_ascii=False)
        rows[f] = len(df)
    open(os.path.join(out_dir, "sql", "schema.sql"), "w", encoding="utf-8", newline="\n").write(ddl())
    open(os.path.join(out_dir, "sql", "seed.sql"), "w", encoding="utf-8", newline="\n").write(seed_sql(P))
    gt = R["ground_truth"].sort_values("gt_id")
    gt.to_csv(os.path.join(out_dir, "ground_truth", "ground_truth.csv"), index=False, lineterminator="\n")
    gt.to_json(os.path.join(out_dir, "ground_truth", "ground_truth.json"), orient="records", indent=1)
    a = R["analysis"].copy(); a["flag"] = a["flag"].astype(int)
    a.to_csv(os.path.join(out_dir, "outputs", "pay_gap_analysis.csv"), index=False, lineterminator="\n")
    json.dump(metrics, open(os.path.join(out_dir, "outputs", "evaluation_metrics.json"), "w", encoding="utf-8", newline="\n"), indent=2, sort_keys=True, default=str)
    json.dump(validation, open(os.path.join(out_dir, "outputs", "validation_summary.json"), "w", encoding="utf-8", newline="\n"), indent=2, sort_keys=True, default=str)
    manifest = dict(
        dataset="Compensation equity - fully synthetic", generator_command=command.split(" --out ")[0] + " --out <OUT_DIR>", seed=cfg.seed, employees=cfg.employees,
        row_counts=rows, ground_truth_rows=len(gt),
        external_data_used=False,
        sources=[], provenance="All values are generated by generator/ with numpy.random.default_rng(seed). No external datasets, "
                              "no personal or confidential data. Public pay-equity literature was used for schema inspiration only.",
        fields_discarded=[], transformations=[], license="MIT (code) / CC0 (generated data)")
    json.dump(manifest, open(os.path.join(out_dir, "manifest", "source_manifest.json"), "w", encoding="utf-8", newline="\n"), indent=2, sort_keys=True)
    sums = {}
    for root, _, files in os.walk(out_dir):
        for fn in files:
            if fn == "checksums.json":
                continue
            p = os.path.join(root, fn); sums[os.path.relpath(p, out_dir).replace(os.sep, "/")] = sha256(p)
    json.dump(dict(sorted(sums.items())), open(os.path.join(out_dir, "checksums.json"), "w", encoding="utf-8", newline="\n"), indent=2)
    return rows
